// Funzione helper per generare username (es. "mario alfio Di Grazia" -> "marioalfio.digrazia")
function generaUsername(nome, cognome) {
    const nomeClean = (nome || "").replace(/\s+/g, "").toLowerCase();
    const cognomeClean = (cognome || "").replace(/\s+/g, "").toLowerCase();
    return `${nomeClean}.${cognomeClean}`;
}

function generaPasswordCasuale(lunghezza = 8) {
    const caratteri = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
    let password = '';
    for (let i = 0; i < lunghezza; i++) {
        password += caratteri.charAt(Math.floor(Math.random() * caratteri.length));
    }
    return password;
}

