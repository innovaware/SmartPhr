async function codificaPassword(password) {
    const saltRounds = 12;
    try {
        const hash = await bcrypt.hash(password, saltRounds);
        return hash;
    } catch (err) {
        console.error("Errore nella codifica della password:", err);
        throw err;
    }
}

// http://[HOST]:[PORT]/api/dipendenti (POST)
// INSERT dipendente su DB
router.post("/", async (req, res) => {
    try {
        const newDip = req.body.dipendente;

        if (!newDip.email || !newDip.mansione) {
            return res.status(400).json({ Error: 'Email or Mansione not defined' });
        }

        // Genera username nel formato nome.cognome (senza spazi e minuscolo)
        const customUsername = generaUsername(newDip.nome, newDip.cognome);

        // Genera e codifica la password mantenendo la logica originaria
        const passwordAutoGenerated = generaPasswordCasuale(8);
        const pwd = await codificaPassword(passwordAutoGenerated);

        // Crea e salva il nuovo dipendente
        const dipendente = new Dipendenti(newDip);
        const result = await dipendente.save();

        // Crea e salva il nuovo utente associato al customUsername
        const user = new User({
            username: customUsername,
            password: pwd,
            active: true,
            role: newDip.mansione,
            dipendenteID: result._id,
            firma: result.nome + " " + result.cognome
        });
        const userResult = await user.save();

        // Mailer SMTP (Invio Diretto)
        const clientMailerService = req.app.get("mailer");
        const clientMailerDisabled = req.app.get("mailerDisabled");

        console.log("clientMailerDisabled: ", clientMailerDisabled);
        if (clientMailerService && !clientMailerDisabled) {
            console.log("Pronto per invio mail a:", newDip.email);

            const emailSubject = "Creazione Account - Credenziali di Accesso";
            const emailHtmlBody = `
                <h2>Benvenuto/a ${newDip.nome} ${newDip.cognome},</h2>
                <p>Il tuo account e\' stato creato con successo all'interno del sistema.</p>
                <p>Ecco le tue credenziali per effettuare il primo accesso:</p>
                <ul>
                    <li><strong>Username:</strong> ${customUsername}</li>
                    <li><strong>Password temporanea:</strong> ${passwordAutoGenerated}</li>
                </ul>
                <p>Ti consigliamo di cambiare la password al primo accesso.</p>
                <br>
                <p>Cordiali saluti,<br><em>Lo Staff</em></p>
            `;

            const mailOptions = {
                from: process.env.SMTP_FROM || '"Gestionale Personale - La Rinascita" <innovawaresrl@gmail.com>',
                to: newDip.email,
                subject: emailSubject,
                html: emailHtmlBody
            };

            clientMailerService.sendMail(mailOptions, (error, info) => {
                if (error) {
                    console.error("Errore durante l'invio dell'email via SMTP:", error);
                } else {
                    console.log("Email inviata con successo! ID messaggio:", info.messageId);
                }
            });
        }

        const usr = res.locals.auth;

        const getDipendente = () => {
            return Dipendenti.findById(usr.dipendenteID);
        };

        const dip = await getDipendente();

        const log = new Log({
            data: new Date(),
            operatore: dip.nome + " " + dip.cognome,
            operatoreID: usr.dipendenteID,
            className: "Dipendente",
            operazione: "Inserimento dipendente: " + dipendente.cognome + " " + dipendente.nome,
        });
        console.log("log: ", log);
        const resultLog = await log.save();

        res.status(200).json(result);
    } catch (err) {
        console.error("Errore durante l'inserimento del dipendente:", err);
        res.status(500).json({ Error: err.message || 'Errore interno del server' });
    }
});

