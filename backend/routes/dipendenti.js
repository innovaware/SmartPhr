router.delete("/:id", async (req, res) => {
    try {
        const { id } = req.params;

        // 1. Elimina l'utenza associata al dipendente
        const deletedUser = await User.deleteOne({ dipendenteID: id });
        console.log("Utente eliminato:", deletedUser);

        // 2. Elimina il dipendente
        const dipendente = await Dipendenti.findByIdAndDelete(id);

        redisClient = req.app.get("redis");
        redisDisabled = req.app.get("redisDisabled");

        if (redisClient != undefined && !redisDisabled) {
            let searchTerm = `DIPENDENTEBY${id}`;
            redisClient.del(searchTerm);
            searchTerm = `DIPENDENTE${id}`;
            redisClient.del(searchTerm);
        }

        const usr = res.locals.auth;

        const getDipendente = () => {
            return Dipendenti.findById(usr.dipendenteID);
        };

        const dip = await getDipendente();

        const log = new Log({
            data: new Date(),
            operatore: dip.nome + " " + dip.cognome,
            operatoreID: usr.dipendenteID,
            className: "Dipendente",
            operazione: "Eliminazione dipendente: " + (dipendente ? dipendente.cognome + " " + dipendente.nome : id),
        });
        console.log("log: ", log);
        const resultLog = await log.save();

        res.status(200).json({
            message: "Dipendente e utenza associata eliminati con successo",
            dipendente: dipendente
        });
    } catch (err) {
        console.error("Errore durante l'eliminazione del dipendente/utente:", err);
        res.status(500).json({ Error: err.message || err });
    }
});

